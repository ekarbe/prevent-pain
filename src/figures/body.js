export const silhouette = (() => {
  const pt = (p) => `${p[0]} ${p[1]}`;
  const mirror = (p) => `${160 - p[0]} ${p[1]}`;
  let d = `M ${pt(HALF[0][0])}`;
  for (const s of HALF) d += ` C ${pt(s[1])}, ${pt(s[2])}, ${pt(s[3])}`;
  for (let i = HALF.length - 1; i >= 0; i--) {
    const s = HALF[i];
    d += ` C ${mirror(s[2])}, ${mirror(s[1])}, ${mirror(s[0])}`;
  }
  return `${d} Z`;
})();

